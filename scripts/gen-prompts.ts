import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * Model-facing prompts live as one Markdown file each in `apps/server/src/prompts/`; this inlines
 * them into `prompts.generated.ts`. A generated module is the one mechanism that works under `tsx`
 * (dev, which cannot import `.md`), vitest, esbuild and `tsc` alike. `pnpm build` regenerates it;
 * `--check` fails when the committed file is stale.
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const directory = resolve(root, 'apps/server/src/prompts');
const output = resolve(directory, 'prompts.generated.ts');

export function generatePrompts(): string {
  const entries = readdirSync(directory).filter(name => name.endsWith('.md')).sort()
    .map(name => `  ${JSON.stringify(name.slice(0, -3))}: ${JSON.stringify(readFileSync(resolve(directory, name), 'utf8').replace(/\n$/, ''))},`);
  return `// Generated by scripts/gen-prompts.ts from the Markdown files beside it. Do not edit.\nexport const PROMPT_SOURCES = {\n${entries.join('\n')}\n} as const;\n`;
}

/** Writes only on a change, so a build of a clean tree leaves it clean. Returns whether it wrote. */
export function writePrompts(): boolean {
  const next = generatePrompts();
  let current: string | undefined;
  try { current = readFileSync(output, 'utf8'); } catch { /* written below */ }
  if (current === next) return false;
  writeFileSync(output, next);
  return true;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(output, 'utf8'); } catch { /* stale below */ }
    if (current !== generatePrompts()) { console.error('gen:prompts: prompts.generated.ts is stale. Run `tsx scripts/gen-prompts.ts`.'); process.exit(1); }
    console.log('gen:prompts: up to date.');
  } else console.log(writePrompts() ? 'gen:prompts: wrote prompts.generated.ts' : 'gen:prompts: up to date.');
}
