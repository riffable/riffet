import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as budgets from '../packages/contracts/src/budgets.js';

/**
 * Writes `packages/contracts/src/budgets.ts` into `Budgets.kt` of the Kotlin contracts module, so the
 * Kotlin client, Android, iOS and the Mac app (through RiffetKit) read the same numbers as the web
 * and the server (docs/guide/performance.md §2). Nested objects flatten to SCREAMING_SNAKE names:
 * `LANE_WINDOW.mac.rows` → `LANE_WINDOW_MAC_ROWS`. `--check` fails when the committed file is stale.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const out = resolve(root, 'apps/mobile/contracts/src/commonMain/kotlin/riffet/contracts/Budgets.kt');

const snake = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();

function flatten(prefix: string, value: unknown, lines: string[]): void {
  if (typeof value === 'number') {
    if (!Number.isSafeInteger(value)) throw new Error(`gen:budgets: ${prefix} is not an integer`);
    // Byte counts are Long, so arithmetic on them cannot overflow Int.
    const literal = Math.abs(value) > 2 ** 31 - 1 || /BYTES/.test(prefix) ? `${value}L` : `${value}`;
    lines.push(`const val ${prefix} = ${literal.replace(/\B(?=(\d{3})+(?!\d))/g, '_')}`);
    return;
  }
  if (!value || typeof value !== 'object') throw new Error(`gen:budgets: ${prefix} is not a number or object`);
  for (const [key, field] of Object.entries(value)) flatten(prefix ? `${prefix}_${snake(key)}` : snake(key), field, lines);
}

const lines: string[] = [];
for (const [name, value] of Object.entries(budgets)) flatten(name, value, lines);

const text = [
  '// Generated by scripts/gen-budgets.ts from packages/contracts/src/budgets.ts — do not edit by hand.',
  '// What each value means is documented there and in docs/guide/performance.md §2.',
  '@file:Suppress("unused")',
  '',
  'package riffet.contracts',
  '',
  ...lines,
  '',
].join('\n');

const current = (() => { try { return readFileSync(out, 'utf8'); } catch { return ''; } })();
if (check) {
  if (current !== text) {
    console.error(`gen:budgets: ${relative(root, out)} is stale; run pnpm gen:budgets`);
    process.exit(1);
  }
} else if (current !== text) {
  writeFileSync(out, text);
  console.log(`gen:budgets: wrote ${relative(root, out)}`);
}
