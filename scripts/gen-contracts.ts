import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod/v4';
import { compareSnapshots, type ContractSnapshot, type CompatibilityBreak, type SnapshotContract } from '../packages/contracts/src/schema/compat.js';
import { CONTRACTS, type ContractDefinition } from '../packages/contracts/src/schema/index.js';

/**
 * Generates the contract schema artifacts from the zod registry:
 *
 * - `packages/contracts/schema/released/<package.json version>.json`: a JSON Schema snapshot of
 *   every registered contract, for comparing releases.
 * - `apps/mobile/contracts/src/commonTest/kotlin/riffet/contracts/ContractFixtures.kt` and
 *   `apps/mobile/contracts/fixtures/swift/contract-fixtures.{max,min,future}.json`: `max` (every
 *   field, branch and enum value), `min` (required fields only) and `future` (an unknown field in
 *   every object, plus unknown values for enums the receiving client keeps) fixtures. Kotlin reads
 *   them from `ContractFixtureTest`; the Swift files are plain JSON for the XCTest target.
 *
 * `--check` regenerates in memory and exits 1 when a committed artifact differs, or when the
 * registry is not additive against the latest snapshot in `packages/contracts/schema/released/`
 * (see `packages/contracts/src/schema/compat.ts`). A breaking change is recorded by releasing a new
 * version: run `pnpm version:bump <version>`, then `pnpm gen:contracts`; the new snapshot file is
 * the next baseline, and the older one stays for comparison. `additionalProperties: false` is
 * removed from the snapshot: the server ignores unknown input fields, and an additive field must not
 * read as a break.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')) as { name: string; version: string };
const kotlinOut = resolve(root, 'apps/mobile/contracts/src/commonTest/kotlin/riffet/contracts/ContractFixtures.kt');
const swiftDir = resolve(root, 'apps/mobile/contracts/fixtures/swift');
const snapshotOut = resolve(root, `packages/contracts/schema/released/${pkg.version}.json`);

type JsonSchema = Record<string, unknown>;
type Fixture = [name: string, payload: unknown];

const UNKNOWN_ENUM = 'future-value';

// ── JSON Schema snapshot ────────────────────────────────────────────────────────────────────

function openObjects(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(openObjects);
  if (!value || typeof value !== 'object') return value;
  const object = Object.fromEntries(Object.entries(value as JsonSchema).map(([key, field]) => [key, openObjects(field)]));
  // zod marks every strict object as closed; this API has always ignored unknown fields.
  if (object.type === 'object' && object.additionalProperties === false) delete object.additionalProperties;
  // zod 4.6 writes a union of primitives as `type: [...]` and a discriminated union as `oneOf`; the
  // snapshots, the compatibility rules and the fixture branches all read unions as `anyOf`.
  if (Array.isArray(object.oneOf) && !object.anyOf) {
    object.anyOf = object.oneOf;
    delete object.oneOf;
  }
  if (Array.isArray(object.type) && object.type.length > 1) {
    const { type, ...rest } = object;
    return { anyOf: (type as unknown[]).map(item => ({ type: item })), ...rest };
  }
  return object;
}

function jsonSchema(definition: ContractDefinition): JsonSchema {
  return openObjects(z.toJSONSchema(definition.schema, { io: 'output', reused: 'inline' })) as JsonSchema;
}

const schemas = new Map(Object.entries(CONTRACTS).map(([name, definition]) => [name, jsonSchema(definition)]));

const snapshotData = {
  $comment: 'Generated by scripts/gen-contracts.ts from packages/contracts/src/schema — do not edit by hand.',
  package: pkg.name,
  version: pkg.version,
  contracts: Object.fromEntries(Object.entries(CONTRACTS).map(([name, definition]) => [name, {
    direction: definition.direction,
    ...(definition.openEnums ? { openEnums: true } : {}),
    schema: schemas.get(name)!,
  } satisfies SnapshotContract])),
};
const snapshot = `${JSON.stringify(snapshotData, null, 2)}\n`;

// ── Fixture generation ─────────────────────────────────────────────────────────────────────

type Mode = 'max' | 'min';
interface BuildOptions {
  mode: Mode;
  /** Branch or enum index keyed by the schema path a choice sits at. */
  pick?: Record<string, number>;
  /** Return an unknown value for every string enum (a newer server's value). */
  unknownEnums?: boolean;
}

const unionBranches = (schema: JsonSchema): JsonSchema[] | undefined => {
  const branches = schema.anyOf ?? schema.oneOf;
  return Array.isArray(branches) ? branches as JsonSchema[] : undefined;
};

function chosenBranch(schema: JsonSchema, path: string, options: BuildOptions): number {
  const branches = unionBranches(schema)!;
  const picked = options.pick?.[path];
  if (picked !== undefined && picked < branches.length) return picked;
  // A nullable field's meaningful shape is the non-null branch.
  const nonNull = branches.findIndex(branch => branch.type !== 'null');
  return nonNull === -1 ? 0 : nonNull;
}

function numericValue(schema: JsonSchema): number {
  const exclusive = typeof schema.exclusiveMinimum === 'number' ? schema.exclusiveMinimum : undefined;
  const minimum = typeof schema.minimum === 'number' ? schema.minimum : 0;
  return Math.max(1, Math.floor(exclusive !== undefined ? exclusive + 1 : minimum));
}

function sample(schema: JsonSchema | undefined, options: BuildOptions, path = '$'): unknown {
  if (!schema) return null;
  if ('const' in schema) return schema.const;
  if (Array.isArray(schema.enum)) {
    if (options.unknownEnums) return typeof schema.enum[0] === 'number' ? 999 : UNKNOWN_ENUM;
    return schema.enum[options.pick?.[path] ?? 0] ?? schema.enum[0];
  }
  const branches = unionBranches(schema);
  if (branches) return sample(branches[chosenBranch(schema, path, options)], options, path);
  if (Array.isArray(schema.allOf)) {
    const values = schema.allOf.map((branch, index) => sample(branch as JsonSchema, options, `${path}.allOf[${index}]`));
    return values.every(value => value && typeof value === 'object' && !Array.isArray(value))
      ? Object.assign({}, ...values) : values[0] ?? null;
  }
  const type = Array.isArray(schema.type) ? schema.type.find(item => item !== 'null') : schema.type;
  switch (type) {
    case 'object': {
      const properties = (schema.properties ?? {}) as Record<string, JsonSchema>;
      const required = new Set(Array.isArray(schema.required) ? schema.required as string[] : []);
      const object: Record<string, unknown> = {};
      const keys = Object.keys(properties);
      if (!keys.length && schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        // A `Record<...>` map: a closed enum key set must list every key in both modes.
        const propertyNames = schema.propertyNames as JsonSchema | undefined;
        const names = Array.isArray(propertyNames?.enum) ? propertyNames.enum as string[] : ['key'];
        for (const name of names) object[name] = sample(schema.additionalProperties as JsonSchema, options, `${path}.*`);
        return object;
      }
      for (const key of keys) {
        if (options.mode === 'min' && !required.has(key)) continue;
        object[key] = sample(properties[key], options, `${path}.${key}`);
      }
      return object;
    }
    case 'array': {
      const minItems = typeof schema.minItems === 'number' ? schema.minItems : 0;
      const count = options.mode === 'max' ? Math.max(minItems, 1) : minItems;
      return Array.from({ length: count }, () => sample(schema.items as JsonSchema | undefined, options, `${path}[]`));
    }
    case 'integer':
    case 'number': return numericValue(schema);
    case 'boolean': return true;
    case 'null': return null;
    case 'string': {
      // A pattern's literal prefix is the only part a generic sample can honor (`^sub:` -> `sub:value`).
      const pattern = typeof schema.pattern === 'string' ? schema.pattern : '';
      if (pattern.startsWith('^')) {
        const literal = pattern.slice(1).match(/^[^\\^$.*+?()[\]{}|]+/)?.[0];
        if (literal) return `${literal}value`;
      }
      return 'text';
    }
    default: return null;
  }
}

interface Choice { path: string; index: number; label: string }

function choicePoints(schema: JsonSchema | undefined, path = '$', out: Choice[] = [], depth = 0, maxDepth = Number.POSITIVE_INFINITY): Choice[] {
  if (!schema || depth > maxDepth) return out;
  if (Array.isArray(schema.enum)) {
    for (let index = 1; index < schema.enum.length; index += 1) out.push({ path, index, label: `${path}=${String(schema.enum[index])}` });
    return out;
  }
  if ('const' in schema) return out;
  const branches = unionBranches(schema);
  if (branches) {
    for (let index = 1; index < branches.length; index += 1) out.push({ path, index, label: `${path}=branch${index}` });
    for (const branch of branches) choicePoints(branch, path, out, depth + 1, maxDepth);
    return out;
  }
  if (Array.isArray(schema.allOf)) {
    for (const branch of schema.allOf) choicePoints(branch as JsonSchema, path, out, depth + 1, maxDepth);
    return out;
  }
  if (schema.type === 'object' || schema.properties) {
    for (const [key, property] of Object.entries((schema.properties ?? {}) as Record<string, JsonSchema>)) {
      choicePoints(property, `${path}.${key}`, out, depth + 1, maxDepth);
    }
    if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
      choicePoints(schema.additionalProperties as JsonSchema, `${path}.*`, out, depth + 1, maxDepth);
    }
  } else if (schema.type === 'array') {
    choicePoints(schema.items as JsonSchema | undefined, `${path}[]`, out, depth + 1, maxDepth);
  }
  return out;
}

/** The union branch a generated payload belongs to, by required keys and literal discriminants. */
function branchFor(value: Record<string, unknown>, branches: JsonSchema[]): JsonSchema {
  return branches.find(branch => {
    const required = Array.isArray(branch.required) ? branch.required as string[] : [];
    if (!required.every(key => key in value)) return false;
    return Object.entries((branch.properties ?? {}) as Record<string, JsonSchema>)
      .every(([key, property]) => !('const' in property) || value[key] === property.const);
  }) ?? branches[0]!;
}

/**
 * A newer server may add a field to any object; maps already hold numbers, so the same value fits
 * both. A map with a closed enum key set (`Record<SessionState, number>`) accepts no extra key.
 */
function withFutureField(value: unknown, schema?: JsonSchema): unknown {
  if (Array.isArray(value)) {
    const items = schema?.type === 'array' ? schema.items as JsonSchema | undefined : undefined;
    return value.map(item => withFutureField(item, items));
  }
  if (!value || typeof value !== 'object') return value;
  let objectSchema = schema;
  const branches = objectSchema ? unionBranches(objectSchema) : undefined;
  if (branches) objectSchema = branchFor(value as Record<string, unknown>, branches);
  const properties = (objectSchema?.properties ?? {}) as Record<string, JsonSchema>;
  const map = objectSchema?.propertyNames !== undefined && objectSchema?.additionalProperties !== undefined;
  const object = Object.fromEntries(Object.entries(value).map(([key, field]) => [
    key, withFutureField(field, properties[key] ?? (map ? objectSchema!.additionalProperties as JsonSchema : undefined)),
  ]));
  return map ? object : { ...object, futureField: 4 };
}

/**
 * Replaces every string enum value a schema marks `open: true` with a value this build does not
 * know. The marker is written by `z.enum([...]).meta({ open: true })` for the enums the Kotlin DTO
 * keeps as `UNKNOWN`. A contract-level `openEnums` is handled by `sample` instead.
 */
function withUnknownEnums(value: unknown, schema?: JsonSchema): { value: unknown; changed: boolean } {
  if (Array.isArray(value)) {
    const items = schema?.type === 'array' ? schema.items as JsonSchema | undefined : undefined;
    let changed = false;
    const next = value.map(item => {
      const result = withUnknownEnums(item, items);
      changed = changed || result.changed;
      return result.value;
    });
    return { value: next, changed };
  }
  if (schema && Array.isArray(schema.enum) && schema.open === true) {
    return { value: typeof value === 'number' ? 999 : UNKNOWN_ENUM, changed: true };
  }
  if (!value || typeof value !== 'object') return { value, changed: false };
  let objectSchema = schema;
  const branches = objectSchema ? unionBranches(objectSchema) : undefined;
  if (branches) objectSchema = branchFor(value as Record<string, unknown>, branches);
  const properties = (objectSchema?.properties ?? {}) as Record<string, JsonSchema>;
  const map = objectSchema?.propertyNames !== undefined && objectSchema?.additionalProperties !== undefined;
  let changed = false;
  const next = Object.fromEntries(Object.entries(value).map(([key, field]) => {
    const result = withUnknownEnums(field, properties[key] ?? (map ? objectSchema!.additionalProperties as JsonSchema : undefined));
    changed = changed || result.changed;
    return [key, result.value];
  }));
  return { value: next, changed };
}

const maxFixtures: Fixture[] = [];
const minFixtures: Fixture[] = [];
const futureFixtures: Fixture[] = [];
const unknownEnumFixtures: Fixture[] = [];

for (const [name, definition] of Object.entries(CONTRACTS)) {
  const schema = schemas.get(name)!;
  const primary = sample(schema, { mode: 'max' });
  const names = new Set<string>();
  const payloads = new Set<string>();
  const add = (fixtureName: string, payload: unknown) => {
    const key = JSON.stringify(payload);
    if (payloads.has(key)) return;
    payloads.add(key);
    let unique = fixtureName, suffix = 2;
    while (names.has(unique)) unique = `${fixtureName}~${suffix++}`;
    names.add(unique);
    maxFixtures.push([unique, payload]);
  };
  add(name, primary);
  const maxDepth = definition.choices === 'shallow' ? 1 : Number.POSITIVE_INFINITY;
  for (const choice of choicePoints(schema, '$', [], 0, maxDepth)) {
    add(`${name}#${choice.label}`, sample(schema, { mode: 'max', pick: { [choice.path]: choice.index } }));
  }
  minFixtures.push([name, sample(schema, { mode: 'min' })]);
  if (definition.openEnums) {
    const unknown = sample(schema, { mode: 'max', unknownEnums: true });
    if (JSON.stringify(unknown) !== JSON.stringify(primary)) unknownEnumFixtures.push([`${name}#unknown-enum`, unknown]);
  } else {
    // One payload carrying an unknown value for every enum the schema marks open. The marker is
    // written by `z.enum([...]).meta({ open: true })` for the enums the Kotlin DTO keeps as UNKNOWN.
    const unknown = withUnknownEnums(primary, schema);
    if (unknown.changed) unknownEnumFixtures.push([`${name}#unknown-enum`, unknown.value]);
  }
}

for (const [name, payload] of maxFixtures) {
  futureFixtures.push([name, withFutureField(payload, schemas.get(name.split('#')[0]!.split('~')[0]!))]);
}
futureFixtures.push(...unknownEnumFixtures);

// ── Emit ───────────────────────────────────────────────────────────────────────────────────

/** A Kotlin raw string cannot escape anything, so `$` becomes a template and `"""` cannot occur. */
function rawString(json: string): string {
  if (json.includes('"""')) throw new Error('fixture JSON contains """, which a Kotlin raw string cannot hold');
  return `"""${json.replace(/\$/g, '${"$"}')}"""`;
}

const kotlinEntries = (fixtures: Fixture[]) => fixtures.map(([name, payload]) => `"${name}" to ${rawString(JSON.stringify(payload))}`);
const kotlinSource = [
  '// Generated by scripts/gen-contracts.ts — do not edit by hand. Run `pnpm gen:contracts`.',
  '// `max` carries every field and the branches/enum values the contract enumerates; `min` only',
  '// required fields; `future` is what a newer server may send. The name before `#` selects the type;',
  '// see ContractFixtureTest.',
  'package riffet.contracts',
  '',
  'internal val CONTRACT_MAX_FIXTURES: List<Pair<String, String>> = listOf(',
  ...kotlinEntries(maxFixtures).map(entry => `    ${entry},`),
  ')',
  '',
  'internal val CONTRACT_MIN_FIXTURES: List<Pair<String, String>> = listOf(',
  ...kotlinEntries(minFixtures).map(entry => `    ${entry},`),
  ')',
  '',
  'internal val CONTRACT_FUTURE_FIXTURES: List<Pair<String, String>> = listOf(',
  ...kotlinEntries(futureFixtures).map(entry => `    ${entry},`),
  ')',
  '',
].join('\n');

const swiftJson = (fixtures: Fixture[]) => `${JSON.stringify(Object.fromEntries(fixtures), null, 2)}\n`;

const outputs: Array<[path: string, content: string]> = [
  [snapshotOut, snapshot],
  [kotlinOut, kotlinSource],
  [`${swiftDir}/contract-fixtures.max.json`, swiftJson(maxFixtures)],
  [`${swiftDir}/contract-fixtures.min.json`, swiftJson(minFixtures)],
  [`${swiftDir}/contract-fixtures.future.json`, swiftJson(futureFixtures)],
];

// ── Additive compatibility against the latest released snapshot ─────────────────────────────

const releasedDir = resolve(root, 'packages/contracts/schema/released');

/** Highest MAJOR.MINOR.PATCH file in `released/`; the file itself is only read here. */
function latestReleased(): { path: string; snapshot: ContractSnapshot } | undefined {
  let names: string[];
  try {
    names = readdirSync(releasedDir);
  } catch {
    return undefined;
  }
  const versions = names
    .filter(name => /^\d+\.\d+\.\d+\.json$/.test(name))
    .sort((left, right) => {
      const a = left.slice(0, -'.json'.length).split('.').map(Number);
      const b = right.slice(0, -'.json'.length).split('.').map(Number);
      return a[0]! - b[0]! || a[1]! - b[1]! || a[2]! - b[2]!;
    });
  const name = versions.at(-1);
  if (!name) return undefined;
  const path = resolve(releasedDir, name);
  return { path, snapshot: JSON.parse(readFileSync(path, 'utf8')) as ContractSnapshot };
}

function printBreaks(breaks: CompatibilityBreak[]): void {
  for (const entry of breaks) {
    console.error(`  ${entry.contract}${entry.path}: ${entry.rule} — ${entry.message}`);
  }
}

const previous = latestReleased();
let breakingAtCurrentVersion = false;
if (previous) {
  const current: ContractSnapshot = { version: pkg.version, contracts: snapshotData.contracts as Record<string, SnapshotContract> };
  const breaks = compareSnapshots(previous.snapshot, current);
  const versionChanged = previous.snapshot.version !== pkg.version;
  if (breaks.length) {
    console.error(`gen:contracts: ${breaks.length} breaking change(s) against the latest released snapshot ${previous.snapshot.version}:`);
    printBreaks(breaks);
    if (checkOnly) {
      breakingAtCurrentVersion = true;
    } else if (versionChanged) {
      console.log(`gen:contracts: allowed by the version change ${previous.snapshot.version} -> ${pkg.version}; the new snapshot records them.`);
    } else {
      console.error(`gen:contracts: breaking changes need a new released version. Run \`pnpm version:bump <version>\` and then \`pnpm gen:contracts\`; the new snapshot under packages/contracts/schema/released/ is the next baseline.`);
      breakingAtCurrentVersion = true;
    }
  } else {
    console.log(`gen:contracts: additive against the latest released snapshot ${previous.snapshot.version}.`);
  }
}

if (breakingAtCurrentVersion) process.exit(1);

let stale = false;
for (const [path, generated] of outputs) {
  const name = relative(root, path);
  if (checkOnly) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* reported as stale below */ }
    if (current !== generated) {
      console.error(`gen:contracts: ${name} is stale. Run \`pnpm gen:contracts\` and commit the result.`);
      stale = true;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, generated);
    console.log(`gen:contracts: wrote ${name}`);
  }
}
if (stale) process.exit(1);
if (checkOnly) console.log('gen:contracts: schema snapshot and fixtures are up to date.');
