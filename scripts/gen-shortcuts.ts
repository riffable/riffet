import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RESERVED_CHORDS, SHORTCUTS } from '../packages/contracts/src/shortcuts.js';

/**
 * Writes the Mac's side of `packages/contracts/src/shortcuts.ts` into `Shortcuts.generated.swift`: the ids,
 * scopes, whether each is rebindable, the `mac` default chords and the chords the Mac reserves. The menus,
 * the settings list, the plugin deny-list and the conflict checks read it (docs/MACOS.md, 快捷键).
 * `--check` fails when the committed file is stale.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const out = resolve(root, 'apps/macos/Riffet/Services/Shortcuts.generated.swift');

const swiftString = (value: string) => JSON.stringify(value);
const mac = SHORTCUTS.flatMap((shortcut) => {
  const defaults = (shortcut.defaults as { mac?: readonly string[] }).mac;
  return defaults ? [{ id: shortcut.id, scope: shortcut.scope, customizable: shortcut.customizable, defaults }] : [];
});

const text = [
  '// Generated by scripts/gen-shortcuts.ts from packages/contracts/src/shortcuts.ts — do not edit by hand.',
  '',
  'enum ShortcutScope: String, CaseIterable {',
  "    case workbench, tabs, session, files, global",
  '}',
  '',
  'enum ShortcutID: String, CaseIterable {',
  ...mac.map((shortcut) => `    case ${shortcut.id}`),
  '',
  '    var scope: ShortcutScope {',
  '        switch self {',
  ...mac.map((shortcut) => `        case .${shortcut.id}: .${shortcut.scope}`),
  '        }',
  '    }',
  '',
  '    /// False for a family of keys that is one rule rather than one action: listed, taken, not rebound.',
  '    var customizable: Bool {',
  '        switch self {',
  ...mac.map((shortcut) => `        case .${shortcut.id}: ${shortcut.customizable}`),
  '        }',
  '    }',
  '',
  '    /// The Mac\'s default chords; an empty list is "offered, unbound".',
  '    var defaults: [String] {',
  '        switch self {',
  ...mac.map((shortcut) => `        case .${shortcut.id}: [${shortcut.defaults.map(swiftString).join(', ')}]`),
  '        }',
  '    }',
  '}',
  '',
  '/// Chords the Mac keeps without answering them: the system\'s and the standard menu items\'.',
  `let reservedShortcutChords: [String] = [${RESERVED_CHORDS.mac.map(swiftString).join(', ')}]`,
  '',
].join('\n');

const current = (() => { try { return readFileSync(out, 'utf8'); } catch { return ''; } })();
if (check) {
  if (current !== text) {
    console.error(`gen:shortcuts: ${relative(root, out)} is stale; run pnpm gen:shortcuts`);
    process.exit(1);
  }
} else if (current !== text) {
  writeFileSync(out, text);
  console.log(`gen:shortcuts: wrote ${relative(root, out)}`);
}
