#!/usr/bin/env node
// Writes Riffet/Features/Canvas/Nodes/CanvasIcons.generated.swift: the Lucide glyphs the canvas draws, as
// SVG path data in the 24x24 box, so the native canvas draws the web's own icons. Run from anywhere:
//   node apps/macos/scripts/gen-canvas-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..', '..');
const dir = path.join(repo, 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const out = path.join(here, '..', 'Riffet', 'Features', 'Canvas', 'Nodes', 'CanvasIcons.generated.swift');

// The names of plugins/riffet/canvas/web/icons.tsx and the transcript's tool icons (Timeline.tsx `toolIcons`), by the Lucide icon behind each.
const NAMES = [
  'arrow-right-left', 'fold-horizontal', 'brain', 'clock', 'check', 'circle', 'circle-alert', 'circle-check', 'folder', 'folder-closed',
  'git-branch', 'git-commit-horizontal', 'git-fork', 'globe', 'list-checks', 'paperclip', 'plus', 'search', 'sparkle', 'sparkles',
  'square-terminal', 'message-circle-question', 'wrench', 'file-text', 'file-pen-line', 'trash-2', 'repeat', 'bot', 'loader-circle',
  'minus', 'maximize', 'play', 'target', 'send',
];
// `IconImage` of the canvas plugin is drawn by hand (not Lucide's own `image`), in the same set's style.
const EXTRA = { image: [{ tag: 'rect', a: { x: 3, y: 3, width: 18, height: 18, rx: 2 } }, { tag: 'circle', a: { cx: 9, cy: 9, r: 2 } }, { tag: 'path', a: { d: 'm21 15-3.1-3.1a2 2 0 0 0-2.8 0L6 21' } }] };

const n = (v) => String(Math.round(v * 1e4) / 1e4);
function toPath(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return tag === 'polygon' ? d + 'Z' : d;
    }
    case 'circle': { const { cx, cy, r } = a; return `M${n(cx - r)} ${cy}a${r} ${r} 0 1 0 ${n(2 * r)} 0a${r} ${r} 0 1 0 ${n(-2 * r)} 0`; }
    case 'ellipse': { const { cx, cy, rx, ry } = a; return `M${n(cx - rx)} ${cy}a${rx} ${ry} 0 1 0 ${n(2 * rx)} 0a${rx} ${ry} 0 1 0 ${n(-2 * rx)} 0`; }
    case 'rect': {
      const x = +a.x || 0, y = +a.y || 0, w = +a.width, h = +a.height, r = Math.min(+(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
    default: throw new Error(`unsupported element ${tag}`);
  }
}

const KEYWORDS = new Set(['repeat']);
const camelRaw = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const camel = (name) => (KEYWORDS.has(camelRaw(name)) ? `\`${camelRaw(name)}\`` : camelRaw(name));
const entries = [];
for (const name of NAMES) {
  let file = path.join(dir, `${name}.js`);
  // Some names are aliases that re-export another icon's file.
  const alias = /export \{ default \} from '\.\/([^']+)'/.exec(fs.readFileSync(file, 'utf8'));
  if (alias) file = path.join(dir, alias[1]);
  const { __iconNode } = await import(pathToFileURL(file).href);
  entries.push([name, __iconNode.map(([tag, a]) => toPath(tag, a))]);
}
for (const [name, nodes] of Object.entries(EXTRA)) entries.push([name, nodes.map(({ tag, a }) => toPath(tag, a))]);

let swift = `// Generated by scripts/gen-canvas-icons.mjs from lucide-react's icon nodes. Do not edit by hand.
// Each icon is the SVG path data of its elements in Lucide's 24x24 box.

enum CanvasIcon: String, CaseIterable, Sendable {
${entries.map(([name]) => `    case ${camel(name)} = "${name}"`).join('\n')}

    var paths: [String] {
        switch self {
${entries.map(([name, ds]) => `        case .${camel(name)}: [${ds.map((d) => JSON.stringify(d)).join(', ')}]`).join('\n')}
        }
    }
}
`;
fs.writeFileSync(out, swift);
console.log(`wrote ${path.relative(repo, out)} (${entries.length} icons)`);
