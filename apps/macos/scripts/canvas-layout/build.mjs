// Bundles the canvas's fold and layout into one classic script for JavaScriptCore.
//
// The tool titles the fold writes come from Lingui macros in the web app's own modules, so the build
// does what the web build does: it runs the macro transform (Lingui's native one, with the web's
// config, in the production `id-only` form) and embeds the compiled catalogs of the messages that
// ended up in the bundle, for every locale the app offers.
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { realpathSync } from 'node:fs';
import { basename, dirname, extname, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../../..');
const LOCALES = ['zh-Hans', 'en'];

// Lingui's packages are not all hoisted; resolve them the way its Vite plugin does.
const require = createRequire(realpathSync(resolve(repo, 'node_modules/@lingui/vite-plugin/package.json')));
const native = await import(require.resolve('@lingui/native-tools'));
const { getConfig } = await import(require.resolve('@lingui/conf'));
const cli = await import(require.resolve('@lingui/cli/api'));
const config = getConfig({ configPath: resolve(repo, 'apps/web/lingui.config.ts') });

/** Every message of the web app's catalogs for [locale], source text standing in for missing translations. */
async function messagesOf(locale) {
  const all = {};
  for (const catalog of await cli.getCatalogs(config)) {
    const { messages } = await catalog.getTranslations(locale, { fallbackLocales: config.fallbackLocales, sourceLocale: config.sourceLocale });
    Object.assign(all, messages);
  }
  return all;
}

const used = new Set();
let embedded = '{}';

const plugin = {
  name: 'canvas-lingui',
  setup(b) {
    b.onLoad({ filter: /\.tsx?$/ }, async ({ path }) => {
      if (path.includes('/node_modules/')) return undefined;
      const code = await readFile(path, 'utf8');
      if (!code.includes('@lingui/core/macro')) return undefined;
      const result = await native.transform(code, basename(path), { macro: { descriptorFields: 'id-only', ...native.mapMacroOptions(config) } });
      for (const match of result.code.matchAll(/\bid:\s*"([^"]+)"/g)) used.add(match[1]);
      return { contents: result.code, loader: extname(path) === '.tsx' ? 'tsx' : 'ts', resolveDir: dirname(path) };
    });
    b.onResolve({ filter: /^canvas-lingui-catalogs$/ }, () => ({ path: 'catalogs', namespace: 'canvas-lingui' }));
    b.onLoad({ filter: /.*/, namespace: 'canvas-lingui' }, () => ({ contents: `export default ${embedded};`, loader: 'js' }));
  },
};

const options = {
  entryPoints: [resolve(here, 'entry.ts')],
  bundle: true,
  minify: true,
  charset: 'utf8',
  format: 'iife',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  define: { 'process.env.NODE_ENV': '"production"' },
  alias: { '@contracts': resolve(repo, 'packages/contracts/src/index.ts'), '@': resolve(repo, 'apps/web/src') },
  banner: { js: '// Generated by apps/macos/scripts/build-canvas-layout.sh; do not edit.' },
  legalComments: 'none',
  logLevel: 'warning',
  plugins: [plugin],
  write: false,
};

// The first pass finds which messages the bundle uses; the second embeds exactly those.
await build(options);
const compiled = {};
for (const locale of LOCALES) {
  const all = await messagesOf(locale);
  const picked = Object.fromEntries([...used].filter((id) => id in all).map((id) => [id, all[id]]));
  compiled[locale] = JSON.parse(cli.createCompiledCatalog(locale, picked, { namespace: 'json' }).source).messages;
}
embedded = JSON.stringify(compiled);
const missing = [...used].filter((id) => !(id in compiled['zh-Hans']));
if (missing.length) console.warn(`canvas-layout: ${missing.length} messages have no catalog entry: ${missing.join(', ')}`);

await build({ ...options, outfile: resolve(repo, 'apps/macos/Riffet/Resources/canvas-layout.js'), write: true });
