import type { ModelInputModalities } from '../../../../../packages/contracts/src/index.js';
import { DEFAULT_PROVIDER, parseModelSelection } from './selection.js';

export const BRIDGE_PACKAGE_NAME = '@riffet/dsh-native-bridge';

export interface DshProfilePatchSettings {
  profileName: string;
  apiEndpoint?: string;
  /** Ids the profile curates, in the order the picker shows them. */
  enabledModels?: string[];
  /** Input types the user declared, keyed by the id used in `enabledModels`. */
  modelInputModalities?: ModelInputModalities;
}

/**
 * The launch overlay, composed as the two patches Riffet owns. The user's
 * `cordis.patch.yml` is independent and is never regenerated by Riffet.
 *
 * DSH resolves a model's input types by exact id against its own catalog and treats an id it does
 * not know as text-only — silently, by swapping every image for a text placeholder before the
 * request leaves. A gateway serves ids DSH has never heard of, so declaring "this one takes images"
 * means writing a catalog row for it. `models` is a whole-array replacement, so the override is
 * only written for a profile that has an endpoint to list its ids from; without one DSH's own
 * catalog is the better answer and is left untouched.
 */
export function dshProfilePatch(settings: DshProfilePatchSettings): string {
  const lines = [
    '- insert:',
    '    - id: riffet-dsh-native-bridge',
    `      name: '${BRIDGE_PACKAGE_NAME}'`,
    '      config:',
    '        endpoint: !!js process.env.RIFFET_DSH_BRIDGE_ENDPOINT',
    '        token: !!js process.env.RIFFET_DSH_BRIDGE_TOKEN',
    `        profileName: '${settings.profileName}'`,
  ];
  const catalog = dshCatalogModels(settings);
  if (catalog.length) {
    // Addressed by id alone: the row is inserted by whichever bundle ships the provider, and a
    // name that does not match would make DSH skip the patch with only a boot warning to show it.
    lines.push('', '- id: llm-deepseek', '  config:', '    models:');
    for (const model of catalog) {
      lines.push(
        `      - id: ${yamlString(model.id)}`,
        `        name: ${yamlString(model.id)}`,
        `        inputModalities: [${model.inputModalities.join(', ')}]`,
      );
    }
  }
  return `${lines.join('\n')}\n`;
}

/** One catalog row per id the profile curates, carrying what the user declared for it. */
function dshCatalogModels(settings: Pick<DshProfilePatchSettings, 'apiEndpoint' | 'enabledModels' | 'modelInputModalities'>): Array<{ id: string; inputModalities: string[] }> {
  const declared = settings.modelInputModalities;
  if (!declared || !settings.apiEndpoint) return [];
  // Clients send ids the way the server lists them (`dsh:<provider>:<model>[effort=…]`); the
  // llm-deepseek row is keyed by the bare model, and only that provider's models belong in it.
  const bare = (id: string): string | undefined => {
    try {
      const selection = parseModelSelection(id, DEFAULT_PROVIDER);
      return selection.provider === DEFAULT_PROVIDER ? selection.model : undefined;
    } catch { return undefined; }
  };
  const catalog = new Map<string, string[]>();
  for (const id of settings.enabledModels ?? []) {
    const model = bare(id);
    if (model && !catalog.has(model)) catalog.set(model, ['text']);
  }
  for (const [id, inputModalities] of Object.entries(declared)) {
    const model = bare(id);
    if (model) catalog.set(model, inputModalities);
  }
  return [...catalog].map(([id, inputModalities]) => ({ id, inputModalities }));
}

/** A JSON string is also a valid YAML double-quoted scalar, so ids need no separate escaper. */
function yamlString(value: string): string { return JSON.stringify(value); }
