/**
 * One part of the mark on its 24-unit grid, as `BrandMark.tsx` draws it: the fill with [cutout]
 * punched out even-odd, then the outline stroke on its own path so it does not outline the cutout.
 * The mark is shifted so its optical centre (12.6, 11.8), not the grid's, is the vector's centre.
 */
private fun brandVector(name: String, d: String, cutout: String = "", strokeWidth: Float): ImageVector =
    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {
        group(translationX = -0.6f, translationY = 0.2f) {
            addPath(pathData = addPathNodes(d + cutout), fill = SolidColor(Color.Black), pathFillType = PathFillType.EvenOdd)
            addPath(
                pathData = addPathNodes(d),
                stroke = SolidColor(Color.Black),
                strokeLineWidth = strokeWidth,
                strokeLineJoin = StrokeJoin.Round,
            )
        }
    }.build()

/**
 * The two-colour Riffet mark: [RiffetIcons.BrandMane] in [accent] under [RiffetIcons.BrandBody] in
 * [fg]. Sized by [modifier]; without a size it takes the vectors' 24dp.
 */
@Composable
fun BrandMark(modifier: Modifier = Modifier, fg: Color, accent: Color) {
    Box(modifier, propagateMinConstraints = true) {
        Icon(RiffetIcons.BrandMane, contentDescription = null, tint = accent)
        Icon(RiffetIcons.BrandBody, contentDescription = null, tint = fg)
    }
}
